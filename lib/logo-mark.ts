export type Cross = {
  cx: number;
  cy: number;
  h: number;
  v: number;
  d: number;
  r: number;
};

/** Держит координаты чистыми и одинаковыми на сервере и в браузере. */
const round4 = (n: number) => Math.round(n * 10000) / 10000;

/**
 * Четыре линии перекрестья как готовые координаты. И компонент, и иконки берут
 * их отсюда — так они не могут разойтись, а числа приходят уже округлёнными
 * (без 5.965600000000002 в разметке).
 */
export function crossLines(cross: Cross) {
  const { cx, cy, h, v, d } = cross;
  // Диагональ задана длиной по гипотенузе, в координаты идёт проекция на ось.
  const leg = round4(d / Math.SQRT2);
  const at = (x1: number, y1: number, x2: number, y2: number) => ({
    x1: round4(x1),
    y1: round4(y1),
    x2: round4(x2),
    y2: round4(y2),
  });
  return [
    at(cx - h, cy, cx + h, cy),
    at(cx, cy - v, cx, cy + v),
    at(cx - leg, cy - leg, cx + leg, cy + leg),
    at(cx - leg, cy + leg, cx + leg, cy - leg),
  ];
}

/**
 * Разметка перекрестья строкой — для иконок, которые собираются вне React
 * (app/icon.tsx, app/apple-icon.tsx). Компонент в components/landing/logo.tsx
 * рисует то же самое элементами React из тех же координат.
 */
export function crossMarkup(cross: Cross, line: number, color: string): string {
  const lines = crossLines(cross)
    .map((l) => `<line x1="${l.x1}" y1="${l.y1}" x2="${l.x2}" y2="${l.y2}"/>`)
    .join("");
  return (
    `<g stroke="${color}" stroke-width="${line}">${lines}</g>` +
    `<circle cx="${cross.cx}" cy="${cross.cy}" r="${cross.r}" fill="${color}"/>`
  );
}

/* --------------------------------------------------------------------------
   Иконки (favicon, apple-touch).

   Здесь знак нарисован иначе, и это осознанно. Контур D — залитая обводка 2
   юнита; на 32px favicon это 1.23 css-px, то есть снова подпиксель, а утолстить
   его нельзя — он контурный, для другого веса нужен новый экспорт. Поэтому роль
   рамки берёт на себя плашка (она и так нужна: тонкий тёмный знак на прозрачном
   фоне пропадает на тёмной панели вкладок), а перекрестье получает свой,
   заметно более плотный вес — единственная линия в иконке, и её толщину мы
   контролируем полностью.

   Общее со знаком в шапке: то же перекрестье из четырёх линий в узел, из тех же
   crossLines. Отличается только вес и то, что вместо контура D — плашка.
   -------------------------------------------------------------------------- */

/** Цвета плашки — те же, что были у иконки с буквой D. */
export const ICON_BG = "#080503";
export const ICON_FG = "#fafaf9";

/** Бокс иконки — квадрат, в отличие от знака (49.4×52). */
export const ICON_BOX = 52;

/**
 * Перекрестье иконки: плечи равные (квадратный бокс), вес 3.6 — на 32px это
 * 2.2px, читается уверенно. Узел крупнее пропорционально весу.
 */
export const ICON_LINE = 3.6;
export const ICON_CROSS: Cross = {
  cx: ICON_BOX / 2,
  cy: ICON_BOX / 2,
  h: 15.5,
  v: 15.5,
  d: 15.5,
  r: 3.9,
};

/**
 * SVG иконки строкой. `radiusRatio` — скругление плашки долей от стороны, чтобы
 * favicon и apple-touch выглядели одинаково при разных размерах (в прежней
 * иконке было rx 37 на 180, то есть 37/180).
 */
export function iconSvg(radiusRatio: number): string {
  const r = round4(ICON_BOX * radiusRatio);
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${ICON_BOX}" height="${ICON_BOX}" viewBox="0 0 ${ICON_BOX} ${ICON_BOX}">` +
    `<rect width="${ICON_BOX}" height="${ICON_BOX}" rx="${r}" fill="${ICON_BG}"/>` +
    crossMarkup(ICON_CROSS, ICON_LINE, ICON_FG) +
    `</svg>`
  );
}
