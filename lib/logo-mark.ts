const round4 = (n: number) => Math.round(n * 10000) / 10000;

/**
 * Разметка знака строкой — для иконок, которые собираются вне React. Компонент
 * в components/landing/logo.tsx рисует то же самое элементами React.
 */
export function markMarkup(boost = CURVE_BOOST): string {
  const curves = LOGO_CURVES.map(
    (d) =>
      `<path d="${d}" fill="${LOGO_CURVE}" stroke="${LOGO_CURVE}" stroke-width="${boost}"/>`
  ).join("");
  const dots = LOGO_DOTS.map(
    (d) => `<path d="${d}" fill="${LOGO_ACCENT}"/>`
  ).join("");
  return curves + dots + `<path d="${LOGO_SPARK}" fill="${LOGO_ACCENT}"/>`;
}

/* --------------------------------------------------------------------------
   Иконки (favicon, apple-touch).

   Дуги в иконку не идут вообще: при 32px масштаб 0.34 px/юнит, и даже с
   утолщением они превратятся в кашу — трём тонким лентам с точками на концах
   в 32 пикселя просто негде разместиться. Берём искру: она плотная, читается
   при любом размере и остаётся самым узнаваемым элементом знака.
   -------------------------------------------------------------------------- */

export const ICON_BG = "#080503";
export const ICON_BOX = 52;
/** Поле между плашкой и искрой. */
export const ICON_PAD = 9;

/**
 * SVG иконки строкой. `radiusRatio` — скругление плашки долей от стороны, чтобы
 * favicon и apple-touch выглядели одинаково при разных размерах.
 */
export function iconSvg(radiusRatio: number): string {
  const plateR = round4(ICON_BOX * radiusRatio);
  const inner = ICON_BOX - ICON_PAD * 2;
  const scale = round4(inner / Math.max(SPARK_BOX.w, SPARK_BOX.h));
  const dx = round4(ICON_PAD - SPARK_BOX.x * scale);
  const dy = round4(ICON_PAD - SPARK_BOX.y * scale);
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${ICON_BOX}" height="${ICON_BOX}" viewBox="0 0 ${ICON_BOX} ${ICON_BOX}">` +
    `<rect width="${ICON_BOX}" height="${ICON_BOX}" rx="${plateR}" fill="${ICON_BG}"/>` +
    `<g transform="translate(${dx} ${dy}) scale(${scale})">` +
    `<path d="${LOGO_SPARK}" fill="${LOGO_ACCENT}"/>` +
    `</g>` +
    `</svg>`
  );
}
