/**
 * Deskpoint lockup — знак + слово, целиком в кривых (экспорт 215×51).
 *
 * Знак — окно кабинета: рамка, боковая колонка, верхняя панель с акцентной
 * точкой и две нижние ячейки. Геометрия и обоснование весов — в
 * lib/logo-mark.ts, оттуда же её берут иконки. Слово — залитые контуры из
 * экспорта, поэтому начертание не зависит от загрузки шрифта и не «прыгает» при
 * FOUT.
 *
 * Цвета привязаны к токенам, а не захардкожены: чёрное из экспорта — это
 * currentColor (наследует text-foreground), коньячное #7D4227 —
 * var(--dp-primary) (токен как раз и равен этому значению).
 *
 * Пропорции держатся на font-size: локап занимает 51 юнит по высоте, что при
 * кегле макета даёт 1.3729em — отсюда EM_SCALE. Размер задаётся кеглем на месте
 * вызова (`text-[24px] lg:text-[28px]` в шапке, `text-[26px]` в футере).
 *
 * Предыдущие версии знака (монолинейная D с перекрестьем, ./logo-solid.tsx,
 * ./logo-outline.tsx) — в истории git.
 */

