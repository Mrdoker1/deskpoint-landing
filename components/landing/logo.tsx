/** Бокс локапа в юнитах экспорта. */
const LOCKUP_W = 215;
const LOCKUP_H = 51;

/**
 * em на юнит: локап высотой 51 юнит — это 1.3729em, как и в прежней версии, чтобы
 * размер на местах вызова не пришлось переподбирать.
 */
const EM_SCALE = 1.3729 / LOCKUP_H;
const round4 = (n: number) => Math.round(n * 10000) / 10000;
const emSize = (w: number, h: number) => ({
  width: `${round4(w * EM_SCALE)}em`,
  height: `${round4(h * EM_SCALE)}em`,
});

/** Знак: рамка, три разделителя и акцентная точка — все линии весом MARK_LINE. */
function MarkPaths({ accent }: { accent: string }) {
  const { frame, lines } = markParts(MARK_LINE);
  return (
    <>
      <rect
        x={frame.x}
        y={frame.y}
        width={frame.width}
        height={frame.height}
        rx={frame.rx}
        fill="none"
        stroke="currentColor"
        strokeWidth={MARK_LINE}
      />
      <g stroke="currentColor" strokeWidth={MARK_LINE}>
        {lines.map((l, i) => (
          <line key={i} x1={l.x1} y1={l.y1} x2={l.x2} y2={l.y2} />
        ))}
      </g>
      <circle cx={MARK_DOT.cx} cy={MARK_DOT.cy} r={MARK_DOT.r} fill={accent} />
    </>
  );
}

