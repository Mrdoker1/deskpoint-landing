/**
 * Только знак, без слова. Размер задаётся классом (`h-*`/`w-*`) или кеглем,
 * цвет структуры — currentColor. Акцент можно переопределить: на тёмном фоне
 * коньячный --dp-primary почти сливается, и его осветляют на месте.
 */
export function LogoMark({
  className,
  style,
  accent = ACCENT,
}: {
  className?: string;
  style?: CSSProperties;
  accent?: string;
}) {
  return (
    <svg
      viewBox={`0 0 ${MARK_BOX.w} ${MARK_BOX.h}`}
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      className={className}
      style={style ?? emSize(MARK_BOX.w, MARK_BOX.h)}
    >
      <MarkPaths accent={accent} />
    </svg>
  );
}

export function Logo({ className }: { className?: string }) {
  return (
    <span
      className={`inline-flex items-center leading-none ${className ?? ""}`}
      role="img"
      aria-label="Deskpoint"
    >
      <svg
        viewBox={`0 0 ${LOCKUP_W} ${LOCKUP_H}`}
        xmlns="http://www.w3.org/2000/svg"
        aria-hidden="true"
        className="shrink-0"
        style={emSize(LOCKUP_W, LOCKUP_H)}
      >
        <MarkPaths accent={ACCENT} />
        <WordmarkPaths accent={ACCENT} />
      </svg>
    </span>
  );
}
