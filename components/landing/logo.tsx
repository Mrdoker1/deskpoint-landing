/** Только знак, без слова. Размер задаётся классом (`h-*`/`w-*`) или кеглем. */
export function LogoMark({
  className,
  style,
}: {
  className?: string;
  style?: CSSProperties;
}) {
  return (
    <svg
      viewBox={`0 0 ${MARK_BOX.w} ${MARK_BOX.h}`}
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      className={className}
      style={style ?? emSize(MARK_BOX.w, MARK_BOX.h)}
    >
      <MarkPaths />
    </svg>
  );
}

export function Logo({ className }: { className?: string }) {
  return (
    <span
      className={`inline-flex items-center leading-none ${className ?? ""}`}
      role="img"
      aria-label="Deskpoint"
    >
      <svg
        viewBox={`0 0 ${LOCKUP.w} ${LOCKUP.h}`}
        xmlns="http://www.w3.org/2000/svg"
        aria-hidden="true"
        className="shrink-0"
        style={emSize(LOCKUP.w, LOCKUP.h)}
      >
        <MarkPaths />
        <WordmarkPaths />
      </svg>
    </span>
  );
}
