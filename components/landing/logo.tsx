/** em на юнит: высота «D» (28.1 юнита) даёт 0.728em, как в прежнем локапе. */
const EM_SCALE = 0.728 / 28.1;
const round4 = (n: number) => Math.round(n * 10000) / 10000;
const emSize = (w: number, h: number) => ({
  width: `${round4(w * EM_SCALE)}em`,
  height: `${round4(h * EM_SCALE)}em`,
});

/**
 * Знак: три дуги, точки на их концах и звезда — контуры из экспорта. Дуги и
 * точки утолщены обводкой того же цвета (см. CURVE_BOOST / DOT_BOOST).
 */
function MarkPaths() {
  return (
    <>
      {LOGO_CURVES.map((d, i) => (
        <path
          key={`curve-${i}`}
          d={d}
          fill={LOGO_CURVE}
          stroke={LOGO_CURVE}
          strokeWidth={CURVE_BOOST}
          strokeLinejoin="round"
          strokeLinecap="round"
        />
      ))}
      {LOGO_DOTS.map((d, i) => (
        <path
          key={`dot-${i}`}
          d={d}
          fill={LOGO_ACCENT}
          stroke={LOGO_ACCENT}
          strokeWidth={DOT_BOOST}
          strokeLinejoin="round"
        />
      ))}
      <path d={LOGO_SPARK} fill={LOGO_ACCENT} />
    </>
  );
}

